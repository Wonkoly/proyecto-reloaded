"""Writes godot/runtime/gm.gd: the final `GM` class, adding a stub for every GM.f_* function
the generated code calls that no runtime library implements yet.

Usage: python3 -I gen_gm_stubs.py <godot_dir>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
defined = set()
for f in (root / "runtime").glob("gm_*.gd"):
    defined |= set(re.findall(r"static func (f_\w+)\(", f.read_text()))

call = re.compile(r"\bG\.(f_\w+)\(")


def arg_count(src, start):
    """Number of top-level arguments of the call whose '(' ends at `start`."""
    depth, i, n, any_tok, in_str = 1, start, 0, False, False
    while i < len(src) and depth:
        c = src[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = any_tok = True
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 1:
            n += 1
        elif not c.isspace():
            any_tok = True
        i += 1
    return n + 1 if any_tok else 0


# Max argument count per called function, not counting the leading `s`.
counts = {}
for f in (root / "gen").rglob("*.gd"):
    src = f.read_text()
    for m in call.finditer(src):
        counts[m.group(1)] = max(counts.get(m.group(1), 0), arg_count(src, m.end()) - 1)

missing = sorted(set(counts) - defined)
out = [
    "## Final runtime class used by generated code. Generated by tools/gen_gm_stubs.py:",
    "## functions below are not implemented yet and only log their first call.",
    "class_name GM",
    "extends GMLibFx",
    "",
    "static var _warned: Dictionary = {}",
    "",
    "static func _stub(n: String) -> float:",
    "\tif not _warned.has(n):",
    "\t\t_warned[n] = true",
    '\t\tpush_warning("[GM] unimplemented: " + n)',
    "\treturn 0.0",
    "",
]
for name in missing:
    params = "".join(f", _a{i} = 0.0" for i in range(max(counts[name], 0)))
    out.append(f'static func {name}(s{params}) -> float:\n\treturn _stub("{name[2:]}")\n')
(root / "runtime" / "gm.gd").write_text("\n".join(out))
print(f"{len(counts)} called, {len(defined & set(counts))} implemented, {len(missing)} stubbed: {missing}")
